function pixels(layer: readonly string[], swap?: (c: string) => string) {
  const list: Pixel[] = [];
  layer.forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c !== ".") {
        list.push({ x, y, c: palette[swap ? swap(c) : c] });
      }
    });
  });
  return list;
}

const golden = (c: string) => (c === "b" ? "B" : c === "h" ? "H" : c);

/** Returns the pixels of the character for the given gear stage and mood. */
export function drawBuddy(stage: number, mood: Mood): Pixel[] {
  const list: Pixel[] = [];
  if (stage >= 3) {
    list.push(...pixels(cape));
  }
  list.push(...pixels(body, stage >= 5 ? golden : undefined));
  if (stage >= 2) {
    list.push(...pixels(headband));
  }
  list.push(...pixels(faces[mood]));
  if (stage >= 1) {
    list.push(...pixels(gloves));
  }
  if (stage >= 4) {
    list.push(...pixels(crown));
  }
  if (stage >= 5) {
    list.push(...pixels(sparkles));
  }
  return list;
}
